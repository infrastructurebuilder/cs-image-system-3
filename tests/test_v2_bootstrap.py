def _bytes(out: Path) -> dict[str, bytes]:
    return {p.relative_to(out).as_posix(): p.read_bytes() for p in sorted(out.rglob("*")) if p.is_file()}


def test_every_run_regenerates_the_root_from_the_answers_and_prunes_without_them(world):
    root, make = world
    run = make()
    assert run.run(["identity"], apply=False).ok
    assert not bs.output_dir(root).exists()                         # the frozen fixture carries no answers: nothing
    bs.write_answers(root / bs.ANSWERS_FILE, GITHUB_ANSWERS)
    run = make()
    summary = run.run(["identity"], apply=False)
    assert summary.ok, summary.validation_errors or summary.error
    out = bs.output_dir(root)
    first = _bytes(out)
    assert "main.tf" in first and "bootstrap.auto.tfvars" in first
    assert b"../../../tfmodules/bootstrap_github" in first["main.tf"]  # the fixture's ../tfmodules, re-rooted
    run = make()
    assert run.run(["identity"], apply=False).ok
    assert _bytes(out) == first                                       # deterministic: the same bytes
    (root / bs.ANSWERS_FILE).unlink()
    run = make()
    assert run.run(["identity"], apply=False).ok
    assert not out.exists()                                           # pruned with the answers


def test_a_commit_run_stages_the_root_and_its_tfvars(world):
    root, make = world
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@example.invalid")
    _git(root, "config", "user.name", "t")
    (root / ".gitignore").write_text("*.tfvars\n!generated/bootstrap/bootstrap.auto.tfvars\n*.tfstate\n")
    bs.write_answers(root / bs.ANSWERS_FILE, GITHUB_ANSWERS)
    run = make()
    summary = run.run(["identity"], apply=False, commit=True)
    assert summary.ok and summary.meta_state_commit, summary.error
    staged = _git(root, "ls-tree", "-r", "--name-only", "HEAD", "generated/bootstrap").split()
    assert "generated/bootstrap/main.tf" in staged and "generated/bootstrap/bootstrap.auto.tfvars" in staged
    assert "generated/bootstrap/.gitignore" in staged


def test_config_drift_judges_the_bootstrap_root(tmp_path: Path):
    from cs_image_system.base.commands.emission import config_drift
    root = tmp_path / "cfgtree"
    (root / "cfg").mkdir(parents=True)
    (root / "cfg" / "_config.yml").write_text("config:\n  module_source_base: tfmodules\n")
    bs.write_answers(root / bs.ANSWERS_FILE, GITHUB_ANSWERS)
    bs.regenerate(root)
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@example.invalid")
    _git(root, "config", "user.name", "t")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "the bootstrap root")

    def dry(copy: Path) -> None:           # what a headless dry run does to the copy, for this tree
        bs.regenerate(copy)
    code, lines = config_drift(root, dry_run=dry)
    assert code == 0, lines
    main = root / "generated" / "bootstrap" / "main.tf"
    main.write_text(main.read_text() + "\n# edited by hand\n")
    _git(root, "commit", "-q", "-am", "a hand edit")
    code, lines = config_drift(root, dry_run=dry)
    assert code == 1 and "BEHIND the configuration (1 files)" in lines[0] and any("edited by hand" in ln for ln in lines)
    # and an answer that changed moves the root: the committed one is behind until a run regenerates it
    bs.regenerate(root)                     # back to the honest root
    _git(root, "commit", "-q", "-am", "regenerated")
    answers = bs.read_answers(root / bs.ANSWERS_FILE)
    answers["github"]["production_branch"] = "release"
    bs.write_answers(root / bs.ANSWERS_FILE, answers)
    _git(root, "commit", "-q", "-am", "an answer changed")
    code, lines = config_drift(root, dry_run=dry)
    assert code == 1 and any('"release"' in ln for ln in lines)


