def _git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, text=True).stdout


def _starter_copy(tmp_path: Path, name: str = "standard-aws", remote: str | None = "git@github.com:acme/widgets.git") -> Path:
    root = tmp_path / "tree"
    shutil.copytree(EXAMPLES / name, root)
    _git(root, "init", "-q", "-b", "develop")
    _git(root, "config", "user.email", "t@example.invalid")
    _git(root, "config", "user.name", "t")
    if remote:
        _git(root, "remote", "add", "origin", remote)
    return root


# ------------------------------------------------------------ the question model

def test_questions_defaults_conditions_and_coercion():
    facts = Facts(config_root=Path("."), owner="acme", repo="widgets")
    literal = Question("a", "A?", default="x")
    derived = Question("b", "B?", default=lambda f, a: f.repository)
    gated = Question("c", "C?", kind="bool", default=True, when=lambda a: a.get("a") == "x")
    assert literal.default_for(facts, {}) == "x" and derived.default_for(facts, {}) == "acme/widgets"
    assert gated.applies({"a": "x"}) and not gated.applies({"a": "y"})
    assert gated.coerce("no") is False and gated.coerce("Y") is True
    with pytest.raises(Refused):
        gated.coerce("maybe")
    choice = Question("d", "D?", kind="choice", choices=("s3", "local"), default="s3")
    assert choice.coerce("local") == "local"
    with pytest.raises(Refused):
        choice.coerce("gcs")
    with pytest.raises(ValueError):
        Question("e", "E?", kind="choice")                         # a choice needs choices
    assert parse_remote("git@github.com:acme/widgets.git") == ("acme", "widgets")
    assert parse_remote("https://github.com/acme/widgets") == ("acme", "widgets")
    assert parse_remote("ssh://elsewhere/x.git") is None


def _section(questions, name="probe"):
    return Section(name=name, title=name, questions=tuple(questions), render=lambda a: Rendered())


def test_the_quiet_interview_takes_defaults_and_refuses_what_it_cannot_derive():
    facts = Facts(config_root=Path("."))
    s = _section([Question("repo", "Repository?", default=lambda f, a: f.repository, help="from git remote"),
                  Question("branch", "Branch?", default="main")])
    with pytest.raises(Refused, match=r"probe\.repo: Repository\? -- no default can be derived \(from git remote\)"):
        bs.run_interview([s], facts, quiet=True)
    facts.owner, facts.repo = "acme", "widgets"
    out = bs.run_interview([s], facts, quiet=True)
    assert out == {"probe": {"wanted": True, "repo": "acme/widgets", "branch": "main"}}
    # earlier answers win over the question's default, and --section keeps the others untouched
    prior = {"probe": {"wanted": True, "repo": "acme/other", "branch": "trunk"}, "aws": {"wanted": True, "x": 1}}
    out = bs.run_interview([s], facts, quiet=True, prior=prior)
    assert out["probe"] == {"wanted": True, "repo": "acme/other", "branch": "trunk"} and out["aws"] == {"wanted": True, "x": 1}
    out = bs.run_interview([s], facts, quiet=True, prior={"probe": {"wanted": False}})
    assert out["probe"] == {"wanted": False}                        # a section not wanted asks nothing
    # the interactive path: a scripted asker, the gate first, defaults shown
    asked: list[tuple[str, object]] = []
    def ask(prompt, default, kind, choices):
        asked.append((prompt, default))
        return {"Repository?": "acme/typed"}.get(prompt, default)
    out = bs.run_interview([s], facts, ask=ask)
    assert out["probe"]["repo"] == "acme/typed" and out["probe"]["branch"] == "main"
    assert asked[0][0] == "Do you want the probe section?" and asked[1] == ("Repository?", "acme/widgets")


