def _assigned(text: str, key: str, value: str) -> bool:
    """``key = value`` on a line of HCL, however aligned."""
    return re.search(rf"^\s*{re.escape(key)}\s*=\s*{re.escape(value)}\s*$", text, flags=re.M) is not None

