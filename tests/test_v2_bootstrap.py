def test_a_quiet_interview_over_a_starter_writes_the_answers_and_the_root(tmp_path: Path):
    root = _starter_copy(tmp_path)
    facts = bs.gather(root, gh=False)
    assert facts.repository == "acme/widgets" and facts.module_source_base == "tfmodules"
    assert facts.runtimes and facts.runtimes[0]["name"]             # the starter's raw cfg was read without loading
    answers = bs.run_interview(bs.discover(), facts, quiet=True, only=["github"])
    github = answers["github"]
    assert github["wanted"] and github["repository"] == "acme/widgets" and github["production_branch"] == "main"
    assert github["perform_runtime"] == facts.runtimes[0]["name"] or github["perform_runtime"]
    bs.write_answers(root / bs.ANSWERS_FILE, answers)
    written = bs.regenerate(root)
    out = bs.output_dir(root)
    assert written and sorted(p.name for p in written) == sorted(
        [".gitignore", "README.md", "bootstrap.auto.tfvars", "main.tf", "outputs.tf", "providers.tf", "set-secrets.sh", "variables.tf"])
    main = (out / "main.tf").read_text()
    assert _assigned(main, "source", '"../../tfmodules/bootstrap_github"')   # re-rooted from generated/bootstrap
    assert _assigned(main, "repository", "var.github_repository")
    tfvars = (out / "bootstrap.auto.tfvars").read_text()
    assert _assigned(tfvars, "github_repository", '"acme/widgets"') and _assigned(tfvars, "github_protect_production", "true")
    assert 'backend "local" {}' in (out / "providers.tf").read_text()
    assert os.access(out / "set-secrets.sh", os.X_OK)
    assert "!bootstrap.auto.tfvars" in (out / ".gitignore").read_text()
    # the tfvars is pinned: the answers alone decide the bytes
    pinned = bs.regenerate(root)
    assert pinned and (out / "bootstrap.auto.tfvars").read_text() == tfvars


def test_the_secrets_script_names_every_guide_secret_and_no_value(tmp_path: Path):
    root = _starter_copy(tmp_path)
    bs.write_answers(root / bs.ANSWERS_FILE, GITHUB_ANSWERS)
    bs.regenerate(root)
    script = (bs.output_dir(root) / "set-secrets.sh").read_text()
    guide = (EXAMPLES / "complete" / "CI_SETUP.md").read_text()
    body = guide[guide.index("### 3.7 The secrets"):]
    body = body[:body.index("\n### ", 1)]
    names = set(re.findall(r"^\| `([A-Z0-9_]+)` \|", body, flags=re.M))
    assert names and all(f"from_file {n}" in script or f"from_output {n} " in script for n in names), names
    assert 'DIR="${SECRETS_DIR:-_uncommitted/secrets}"' in script and 'REPO="${REPO:-acme/widgets}"' in script
    assert "AKIA" not in script and "BEGIN" not in script             # no value, ever


