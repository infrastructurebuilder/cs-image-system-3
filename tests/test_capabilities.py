"""Capabilities: identity/storage-type plumbing, activation, the admin user
and launch parameters.

* base images declare capability on two axes; every declared type's plugin
  bakes its prerequisites, dormant; the mandatory admin user carries public
  keys only; the runtime's session mechanism is the other debug path and
  the no-key-no-session dead end hard-fails; the SSM profile wins a bake
  when both profiles are set;
* an instance image using an undeclared type (either axis) hard-fails the
  run; resolution is through pins to the stamped root build; a chain
  inherits the root's stamp;
* an instance image bakes the activation for its OWN owning group;
* launch parameters (mounts, enrollment) are generated by reference,
  recorded in meta-state and immutable after launch; a decommissioned
  instance is whitelisted, then forgotten after the real apply; a dry run
  never asks the registry for a hostname claim.

History: gate 5 (DESIGN §4 phase F1+F2; N9, N11, N24, N26), stage 63
low-hanging items 9 and 10.
"""
