"""V2 gate 5 (DESIGN §4, phase F1+F2): identity/storage-type plumbing,
activation, admin user and launch parameters.

* base images declare capability on two axes; every declared type's plugin
  bakes its prerequisites, dormant; the mandatory admin user carries public
  keys only; the runtime's session mechanism is the other debug path and
  the no-key-no-session dead end hard-fails (N9);
* an instance image using an undeclared type (either axis) hard-fails the
  run (§3F2); resolution is through pins to the stamped root build (N11);
* an instance image bakes the activation for its OWN owning group;
* launch parameters (mounts, enrollment) are generated by reference,
  recorded in meta-state, and immutable after launch (N26).
"""
from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from v2_support import V2Run, copy_config, tree


@pytest.fixture
def v2(tmp_path, monkeypatch):
    run = V2Run(tmp_path, monkeypatch)
    yield run
    run.restore_cwd()


def _write_yaml(path: Path, data) -> None:
    path.write_text(yaml.safe_dump(data, sort_keys=False))


def _prepared(tmp_path, monkeypatch, mutate):
    root = copy_config(tmp_path)
    mutate(root)
    return V2Run(tmp_path, monkeypatch, config_root=root)


def _set_os_builder(root: Path, name: str, **fields) -> None:
    p = root / "cfg" / "os-builders.yml"
    data = yaml.safe_load(p.read_text())
    for ob in data["os_builders"]:
        if ob["name"] == name:
            ob.update(fields)
    _write_yaml(p, data)


def _set_config(root: Path, **fields) -> None:
    p = root / "cfg" / "_config.yml"
    data = yaml.safe_load(p.read_text())
    data["config"].update(fields)
    _write_yaml(p, data)


def _set_runtime(root: Path, name: str, **fields) -> None:
    p = root / "cfg" / "runtime-builders.yml"
    data = yaml.safe_load(p.read_text())
    for rt in data["runtime_builders"]:
        if rt["name"] == name:
            rt.update(fields)
    _write_yaml(p, data)


def _base_build(v2) -> str:
    return (v2.generated / "base-image" / "pckr-ebs-ans" / "image-generation" / "block-000"
            / "pckr-ebs-ans-image-generation-block-000-build.pkr.hcl").read_text()


def _instance_build(v2) -> str:
    return (v2.generated / "instance-image" / "pckr-ebs-ans" / "image-generation" / "block-000"
            / "pckr-ebs-ans-image-generation-block-000-build.pkr.hcl").read_text()


# ----------------------------------------------------------- base images

def test_base_image_bakes_admin_user_and_declared_prerequisites_dormant(v2):
    assert v2.run(["base-image"], apply=False).ok
    build = _base_build(v2)
    # admin user with the public key, sudo, no password
    assert "useradd -m -s /bin/bash csisadmin" in build
    # stage 49: the key is declared encrypted, so the EMISSION carries its
    # ciphertext; `materialize` puts the key itself in the private copy packer
    # builds from, and nothing in the committed tree holds it
    assert "ENC[age:" in build
    assert "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIPlaceholderKey" not in build
    assert "NOPASSWD:ALL" in build
    # okta prerequisites: agent installed, DORMANT
    assert "scaleft-server-tools" in build
    assert "systemctl disable --now sftd" in build
    assert "rm -f /var/lib/sftd/enrollment.token" in build
    # storage prerequisites for every declared type on rhel-8/9 ...
    assert "amazon-efs-utils" in build
    assert "awscli" in build
    # ... and nothing for the type my-deb-11 does not declare
    deb = build.split('only   = ["amazon-ebs.my-deb-11"]')
    deb_section = "".join(s.split("provisioner")[0] for s in deb[1:])
    assert "nfs-common" not in deb_section
    # activation NEVER happens on a base image
    assert "sftd.yaml" not in build and "tx.group" not in build


