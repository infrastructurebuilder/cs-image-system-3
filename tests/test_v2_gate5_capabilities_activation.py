def test_launch_parameters_are_generated_by_reference_and_recorded(v2):
    assert v2.run(["instance-image"], apply=False).ok
    inst = tree(v2.generated / "instance-image" / "open-tofu" / "instance-generation")
    module = inst["open-tofu-instance-generation-instance-test2.tf"]
    assert 'templatefile("${path.module}/user-data-test2.sh.tftpl"' in module
    assert 'data.terraform_remote_state.oktagroups.outputs.group_gids["coops"]' in module
    assert 'data.terraform_remote_state.aws_ebs.outputs.storage_mnt_data.volume_id' in module
    assert '"device_name" = "/dev/xvdf"' in module
    assert "var.sft_enrollment_token" in module
    tpl = inst["user-data-test2.sh.tftpl"]
    # device resolution: legacy name first, Nitro by-id fallback from the
    # volume id (found live: /dev/xvdf never appears on t3/Nitro)
    assert "DEV='/dev/xvdf'" in tpl and "/mnt/data" in tpl
    assert 'ebs["mnt_data"].volume_id' in tpl
    assert "nvme-Amazon_Elastic_Block_Store_" in tpl
    assert 'mkfs -t xfs "$DEV"' in tpl
    assert "chgrp \"$GID\" '/mnt/data/coops'" in tpl and "chmod 2770 '/mnt/data/coops'" in tpl
    assert "/var/lib/sftd/enrollment.token" in tpl
    root = inst["open-tofu-instance-generation.tf"]
    assert 'variable "sft_enrollment_token"' in root and "sensitive = true" in root
    assert 'data "terraform_remote_state" "oktagroups"' in root
    lp = yaml.safe_load((v2.meta_state / "launch-params.yaml").read_text())
    rec = lp["instances"]["test2"]
    assert rec["group"] == "coops" and rec["identity_type"] == "okta"
    assert rec["mounts"][0] == {"storage": "mnt_data", "type": "ebs", "builder": "aws-ebs",
                                "mount_point": "/mnt/data", "group": "coops", "share_mode": "2770",
                                "public_read": False, "device": "/dev/xvdf"}
    assert rec["enrollment"] == {"enrollment": "sftd-token", "server_label": "sftd.tx.group=coops"}
    assert rec["launched"] is False
    assert "token" not in yaml.safe_dump(rec).replace("sftd-token", "").replace("enrollment.token", "")


def test_launch_parameters_are_immutable_after_launch(tmp_path, monkeypatch):
    run = V2Run(tmp_path, monkeypatch)
    try:
        assert run.run(["instance-image"], apply=False).ok
        # simulate the apply that launched test2
        ms = run.ctx.meta_state
        rec = dict(ms.launch_params()["test2"])
        rec["launched"] = True
        rec["launched_run"] = "2026_08_01t00_00_00"
        ms.record_launch_params("test2", rec)
        # same parameters: fine
        assert run.run(["instance-image"], apply=False).ok
        # change the mount point -> hard failure
        p = run.config_root / "instances" / "instances.yaml"
        data = yaml.safe_load(p.read_text())
        data["instances"][1]["storages"][0]["mount_point"] = "/data"
        _write_yaml(p, data)
        run.restore_cwd()
        run2 = V2Run(tmp_path, monkeypatch, config_root=run.config_root)
        summary = run2.run(["instance-image"], apply=False)
        assert not summary.ok
        assert any("launch parameters are immutable after launch" in e and "'test2'" in e
                   for e in summary.validation_errors)
        # ... unless the instance is being replaced by an explicit upgrade
        run2.ctx.meta_state.move_pin("instance", "test2", "ami-0new", run2.ctx.run_id)
        assert run2.run(["instance-image"], apply=False).ok
        cmds = (run2.generated / "instance-image" / "run-instance-image.sh").read_text()
        assert "-replace=module.instance_test2.aws_instance.this" in cmds
        assert "--allow-destroy module.instance_test2.aws_instance.this" in cmds
        run2.restore_cwd()
    finally:
        run.restore_cwd()


def test_decommissioned_instance_is_whitelisted_and_forgotten(tmp_path, monkeypatch):
    def mutate(root: Path):
        ms = root / "meta-state"
        ms.mkdir()
        _write_yaml(ms / "launch-params.yaml", {"instances": {"old_node": {"launched": True, "image": "x"}}})
        _write_yaml(ms / "pins.yaml", {"instances": {"old_node": "ami-0old"}, "images": {}})
    run = _prepared(tmp_path, monkeypatch, mutate)
    try:
        # a DRY run whitelists the destroy but must NOT forget the record yet
        # (finding 53: forgetting at generation let a dry run erase the record
        # before any destroy ran, leaving nothing to whitelist afterwards)
        assert run.run(["instance-image"], apply=False).ok
        cmds = (run.generated / "instance-image" / "run-instance-image.sh").read_text()
        assert "--allow-destroy module.instance_old_node" in cmds
        lp = yaml.safe_load((run.meta_state / "launch-params.yaml").read_text())
        assert "old_node" in lp["instances"]
        pins = yaml.safe_load((run.meta_state / "pins.yaml").read_text())
        assert "old_node" in pins["instances"]
        assert not any(u.get("op") == "decommission" for u in pins.get("upgrades", []))
        # the REAL apply (flag on) destroys through the gate, then forgets
        _set_config(run.config_root, apply_instances=True)
        run.restore_cwd()
        run = V2Run(tmp_path, monkeypatch, config_root=run.config_root)   # reload the flag
        assert run.run(["instance-image"], apply=False).ok
        # simulate the apply that destroyed old_node (the harness's stubbed
        # apply step fires no hooks): the after-apply forget, flag on
        from cs_image_system.base.launch_params import forget_decommissioned
        from cs_image_system.base.lifecycles import Lifecycle
        forget_decommissioned(run.ctx, Lifecycle.INSTANCE_IMAGE)
        lp = yaml.safe_load((run.meta_state / "launch-params.yaml").read_text())
        assert "old_node" not in lp["instances"]
        pins = yaml.safe_load((run.meta_state / "pins.yaml").read_text())
        assert "old_node" not in pins["instances"]
        assert pins["upgrades"][-1]["op"] == "decommission"
    finally:
        run.restore_cwd()


