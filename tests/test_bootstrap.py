    answers = bs.read_answers(root / bs.ANSWERS_FILE)
    answers["github"]["production_branch"] = "release"
    bs.write_answers(root / bs.ANSWERS_FILE, answers)
    _git(root, "commit", "-q", "-am", "an answer changed")
    code, lines = config_drift(root, dry_run=dry)
    assert code == 1 and any('"release"' in ln for ln in lines)


