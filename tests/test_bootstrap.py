def test_config_drift_judges_the_bootstrap_root(tmp_path: Path):
    from cs_image_system.base.commands.emission import config_drift
    root = tmp_path / "cfgtree"
    (root / "cfg").mkdir(parents=True)
    (root / "cfg" / "_config.yml").write_text("config:\n  module_source_base: tfmodules\n")
    bs.write_answers(root / bs.ANSWERS_FILE, GITHUB_ANSWERS)
    bs.regenerate(root)
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@example.invalid")
    _git(root, "config", "user.name", "t")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "the bootstrap root")

    def dry(copy: Path) -> None:           # what a headless dry run does to the copy, for this tree
        bs.regenerate(copy)
    code, lines = config_drift(root, dry_run=dry)
    assert code == 0, lines
    main = root / "generated" / "bootstrap" / "main.tf"
    main.write_text(main.read_text() + "\n# edited by hand\n")
    _git(root, "commit", "-q", "-am", "a hand edit")
    code, lines = config_drift(root, dry_run=dry)
    assert code == 1 and "BEHIND the configuration (1 files)" in lines[0] and any("edited by hand" in ln for ln in lines)
