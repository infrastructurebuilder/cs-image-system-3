def test_the_command_runs_without_loading_and_refuses_by_name_under_quiet(tmp_path: Path):
    from typer.testing import CliRunner

    from cs_image_system.system.cli import app
    root = _starter_copy(tmp_path, remote=None)                      # no remote: the repository has no default
    quiet = ["--root-dir", str(root), "bootstrap", "--quiet", "--section", "github"]
    res = CliRunner().invoke(app, quiet)
    assert res.exit_code == 2 and "refused: github.repository" in res.output, res.output
    assert not (root / bs.ANSWERS_FILE).exists()
    _git(root, "remote", "add", "origin", "https://github.com/acme/widgets.git")
    res = CliRunner().invoke(app, quiet)
    assert res.exit_code == 0, res.output
    assert "sections wanted: github" in res.output and "wrote generated/bootstrap/main.tf" in res.output
    assert "by hand" in res.output and "tofu apply" in res.output
    # the closing lines say who terraform acts as -- for THIS tree's sections, before the commands
    assert "  export GITHUB_TOKEN=$(gh auth token)" in res.output
    assert "GOOGLE_OAUTH_ACCESS_TOKEN" not in res.output and "AWS_PROFILE" not in res.output     # GitHub alone
    assert res.output.index("export GITHUB_TOKEN") < res.output.index("cd generated/bootstrap && tofu init")
    answers = yaml.safe_load((root / bs.ANSWERS_FILE).read_text())
    assert answers["sections"]["github"]["repository"] == "acme/widgets"
    # a second quiet interview keeps the answers (they are the defaults now) and the bytes
    before = _bytes(bs.output_dir(root))
    res = CliRunner().invoke(app, quiet)
    assert res.exit_code == 0 and _bytes(bs.output_dir(root)) == before


def test_set_secrets_refuses_a_secrets_directory_git_would_track(tmp_path):
    """The interview offers
    `_uncommitted/secrets` as never committed; the starters now ignore it, and
    the script refuses, before any secret is read, a directory git does not
    ignore."""
    import subprocess

    from cs_image_system.base.bootstrap.hcl import _secrets_script
    repo = tmp_path / "repo"; repo.mkdir()
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    (repo / ".gitignore").write_text("_uncommitted/\n")
    (repo / "generated" / "bootstrap").mkdir(parents=True)
    script = repo / "generated" / "bootstrap" / "set-secrets.sh"
    script.write_text(_secrets_script([], repository="o/r", secrets_dir="_uncommitted/secrets"))
    tracked = subprocess.run(["bash", str(script)], cwd=repo, capture_output=True, text=True, env={"PATH": os.environ["PATH"], "SECRETS_DIR": "secrets"})
    assert tracked.returncode == 2 and "is not ignored by git" in tracked.stderr, tracked
    ignored = subprocess.run(["bash", str(script)], cwd=repo, capture_output=True, text=True, env={"PATH": os.environ["PATH"]})
    assert ignored.returncode == 0, ignored        # no secret named: nothing to set, and the ignored default passes the check
