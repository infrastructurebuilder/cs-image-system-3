"""The provider-neutral storage root.

One terraform workspace per storage builder, one ``module`` call per
attached storage against the module the provider names, driven by
OpenTofu. Group access is realized by gid REFERENCE: the root reads the
identity workspace's ``group_gids`` output through
``data.terraform_remote_state`` and never carries a literal gid; storages
in requested state ``destroyed`` are omitted (their destruction is the only
destroy the apply gate whitelists); every storage publishes its module
outputs for the instance-image lifecycle to bind to.

The base owns the root's layout and header, the provider requirement and
configuration as hooks, the state-manager binding and the identity
remote-state references, the module calls and their outputs, the
tombstones and archives, the runner lines (fmt, init, validate, then the
transition scripts, the gated plan, gate and apply, and the after-apply
actions), the state query over every declared and recorded storage, and
the ownership test a shared account needs. A provider's root answers the
hooks (which provider, which module, what the module call carries, how a
storage is looked up and re-tagged, what a transition runs) and keeps its
own clients.
"""
from __future__ import annotations

from typing import Any, TypeVar

from cs_image_system.base.basic.builder_base_storage import StorageBuilderBase
from cs_image_system.base.models.executable import ExecutableModel
from cs_image_system.base.models.storage import (
    STORAGE_STATE_ACTIVE,
    STORAGE_STATE_ARCHIVED,
    STORAGE_STATE_DESTROYED,
    Storage,
)
from cs_image_system.contract.assets import AssetSet
from cs_image_system.contract.executables import CFExecutables, ExecutableProtocol
from cs_image_system.contract.group import GroupBuilderProtocol
