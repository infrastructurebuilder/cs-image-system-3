"""GCP storage plugins (GCP increment 3, PLAN.md gates 2-3, 6).

Three capability types on a GCE runtime, each reusing the AWS tofu storage
machinery (one terraform root per builder, module call per storage, gids by
remote-state reference, the storage state machine, the apply gate):

* ``pd`` -- persistent disk, single-attach, POSIX (EBS equivalent);
* ``filestore`` -- NFS, many-attach, POSIX (EFS equivalent; no access
  points, so the per-group subtree is created and chgrp'ed at first mount
  by the launch parameters);
* ``gcs`` -- bucket, many-attach, non-POSIX (S3 equivalent).

The google provider is configured from the runtime builder (project, region,
zone, optional service-account key file). Storage state queries use the
compute client for disks; Filestore/GCS need client libraries that are not
dependencies yet and report as *unavailable*.
"""
