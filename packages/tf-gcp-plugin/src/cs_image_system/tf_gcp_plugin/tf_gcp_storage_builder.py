def google_provider_config(rtb: Any) -> dict[str, Any]:
    """``provider "google"`` arguments from a GCP runtime builder model."""
    model = getattr(rtb, "model", None)
    cfg: dict[str, Any] = {}
    if model is None:
        return cfg
    for src, dst in (("project_id", "project"), ("region", "region"), ("zone", "zone")):
        v = getattr(model, src, None)
        if v:
            cfg[dst] = str(v)
    # Credentials come from the environment only (GOOGLE_APPLICATION_CREDENTIALS
    # or ADC), never from generated IaC -- the same rule as the AWS roots' profile.
    return cfg


class TofuGcpStorageBuilder(TofuStorageBuilderBase[Q]):
    """Base of the GCP storage plugins: the neutral storage root with the
    google provider; everything else is inherited."""

    @classmethod
    def csis_name(cls) -> str:
        return TF_GCP

    # ------------------------------------------------------------ the hooks
    def _provider_name(self) -> str:
        return "google"

    def _provider_source(self) -> str:
        return "hashicorp/google"

    def _provider_config(self, rtb: Any) -> dict[str, Any] | None:
        return google_provider_config(rtb) or None

    def _root_header_lines(self) -> list[str]:
        return [f"# Terraform configuration for GCP storages generated by "
                f"{self.__class__.__name__} ({self.name})"]

    def _runtime(self):
        return self._get_context().runtime_builders.get(self.model.get_runtime_provider(), None)

    def _gcloud(self) -> str:
        """The runtime's declared gcloud (stage 63 item 14) for the lookups and
        the generated scripts (which shell-quote it); a runtime without the
        resolver (a stub) keeps the bare name. The ON-IMAGE gcloud below
        (the gcs prerequisites) is the VM's own and stays a bare name."""
        rtb = self._runtime()
        resolve = getattr(rtb, "gcloud_binary", None)
        return str(resolve()) if callable(resolve) else "gcloud"

    def _project(self) -> str | None:
        from cs_image_system.gcloud_runtime.gcp_utils import resolve_project
        rtb = self._runtime()
        to_cfg: Any = getattr(getattr(rtb, "model", None), "self_to_gcp_client_config", None)
        return resolve_project(cast(dict[str, Any], to_cfg())) if callable(to_cfg) else None

    def _zone(self) -> str | None:
        rtb = self._runtime()
        return getattr(rtb.model, "zone", None) if rtb else None

    @staticmethod
    def _gce_resource_name(name: str) -> str:
        """GCE resource names must match ``[a-z]([-a-z0-9]*[a-z0-9])?`` --
        found live: a disk named ``gce_data`` fails the apply. Same rule the
        packer sources apply via ``gce_name``."""
        from cs_image_system.gcloud_runtime.gcp_packer_source import gce_name
        return gce_name(name)

    def _labels(self, storage: Storage) -> dict[str, str]:
        from cs_image_system.gcloud_runtime.gcp_packer_source import gce_label
        # stage 26: the builder's declared default labels under the item's own
        merged = getattr(self.model, "variables", None)
        base = merged.merged_tags(storage.tags) if merged is not None else dict(storage.tags or {})
        labels = {gce_label(k): gce_label(str(v)) for k, v in base.items()}
        labels["csis_storage"] = gce_label(storage.get_name())
        from cs_image_system.base.lineage import config_tags
        get_ctx: Any = getattr(self, "_get_context", None)      # a stand-in without a context gets no id
        if callable(get_ctx):
            labels.update(config_tags(cast(Any, get_ctx())))   # stage 93: the disk, bucket, share carry the id
        for g in sorted(storage_groups(storage)):
            labels[f"csis_group_{gce_label(g)}"] = "true"
        return labels

    # state query: subclasses that can ask do; the rest are "unavailable"
    def _lookup(self, storage: Storage) -> dict[str, Any] | None:
        raise NotImplementedError(f"{self.__class__.__name__} cannot query storage state yet")

    def _theirs(self, labels: dict[str, Any]) -> bool:
        """Stage 93: a thing of our name whose labels name another
        configuration is not ours (GCE names are unique per zone or project,
        so it stands where ours would)."""
        from cs_image_system.base.lineage import belongs_to_another_configuration
        return belongs_to_another_configuration(self._get_context(), labels)

    @staticmethod
    def _elsewhere_by_labels(labels: dict[str, Any], what: str) -> dict[str, Any]:
        from cs_image_system.base.lineage import owner_of
        return {"present": False, "elsewhere": owner_of(labels), "what": what}


R = TypeVar("R", bound=TofuPdStorageBuilderModel)
class TofuPdStorageBuilder(TofuGcpStorageBuilder[R]):
    @classmethod
    def csis_name(cls) -> str:
        return TF_GCP_PD

    @classmethod
    def capability_type(cls) -> str:
        return "pd"

    def is_zonal(self) -> bool:
        return True     # stage 52: a persistent disk lives in one zone; changing it replaces the volume

    def attachment_cardinality(self) -> str:
        return CARDINALITY_SINGLE

    def base_image_prerequisites(self, os_family: str | None = None) -> list[str]:
        return [f"# storage type 'pd' declared: no prerequisites to bake ({self.get_name()})"]

    # ------------------------------------------------------- launch hooks
    def launch_mount(self, storage: Storage, mapping: Any, index: int) -> dict[str, Any]:
        """GCE names an attached disk ``/dev/disk/by-id/google-<device_name>``;
        the instance root attaches with ``gce_name(<storage>)`` as the device
        name, so the by-id path takes the same sanitised name (finding 50: the
        two once disagreed -- the raw name attached, the sanitised name mounted
        -- and the startup script died at the missing device)."""
        return {"device": "/dev/disk/by-id/google-" + self._gce_resource_name(storage.get_name())}

    def launch_script_lines(self, mount: dict[str, Any], group: str | None) -> list[str]:
        """Wait for the by-id device (it is the stable name, so the fallback
        is the device itself), format when blank, mount, the group's subtree."""
        return [
            *self.mount_header_lines(mount),
            f"DEV='{mount['device']}'",
            'BYID="$DEV"',
            *self.block_device_lines(mount),
            *self.group_subtree_lines(mount, group),
        ]

    def module_dirname(self) -> str:
        return "gcp_storage_pd"

    def retag_storage(self, storage: Storage, tags: dict[str, str]) -> bool:
        from google.cloud import compute_v1  # noqa: PLC0415
        from cs_image_system.gcloud_runtime.gcp_packer_source import gce_label
        from cs_image_system.gcloud_runtime.gcp_utils import make_credentials, resolve_project
        rtb = self._runtime()
        to_cfg: Any = getattr(getattr(rtb, "model", None), "self_to_gcp_client_config", None)
        cfg: dict[str, Any] = cast(dict[str, Any], to_cfg()) if callable(to_cfg) else {}
        project, zone = resolve_project(cfg), self._disk_zone(storage)
        if not project or not zone:
            raise RuntimeError("no project/zone to retag in")
        creds = make_credentials(cfg)
        client = compute_v1.DisksClient(credentials=creds) if creds else compute_v1.DisksClient()
        name = self._gce_resource_name(storage.get_name())
        try:
            d = client.get(project=project, zone=zone, disk=name)
        except Exception as e:  # noqa: BLE001
            if e.__class__.__name__ == "NotFound":
                return False
            raise
        labels = dict(getattr(d, "labels", {}) or {})
        labels.update({gce_label(k): gce_label(str(v)) for k, v in tags.items()})
        client.set_labels(project=project, zone=zone, resource=name,
                          zone_set_labels_request_resource=compute_v1.ZoneSetLabelsRequest(
                              labels=labels, label_fingerprint=getattr(d, "label_fingerprint", None))).result()
        return True

    def _require_script_inputs(self, storage: Storage, **values: str | None) -> None:
        """A generated archive/restore script needs its project (and zone);
        a missing one used to be written as the literal `None` and failed
        only when gcloud ran (stage 63: refused at generation instead)."""
        missing = sorted(k for k, v in values.items() if not v)
        if missing:
            raise ValueError(f"storage '{storage.get_name()}' on builder {self.get_name()}: the archive "
                             f"scripts need {' and '.join(missing)}, and the runtime declares none "
                             "(set `project_id` and `zone` on the GCP runtime)")

    def _disk_zone(self, storage: Storage) -> str | None:
        """Where THIS disk lives: the storage's own ``availability_zone`` when
        declared, the runtime's ``zone`` otherwise, as the EBS builder does
        (stage 63 item 21). `validate` checks the declared zone against the
        runtime and every instance that mounts the disk; the module call, the
        lookup and the archive script all read it here, so a disk pinned to a
        zone is created, found and snapshotted in that zone."""
        declared = getattr(storage, "availability_zone", None)
        return str(declared) if declared else self._zone()

    def module_args(self, storage: Storage) -> dict[str, Any]:
        args: dict[str, Any] = {
            "name": self._gce_resource_name(storage.get_name()),
            "size": getattr(self.model, "size", 100),
            "disk_type": getattr(self.model, "disk_type", "pd-balanced"),
            "labels": self._labels(storage),
        }
        zone = self._disk_zone(storage)
        if zone:
            args["zone"] = zone
        # restore (stage 11.6): recorded archived, declared active -> the disk
        # is created FROM the archive snapshot; the module ignores later drift
        if self._get_context().meta_state.storage_state(storage.get_name()) == STORAGE_STATE_ARCHIVED:
            args["snapshot"] = self.archive_name(storage)
        return args

    # ------------------------------------------------ archived (stage 11.6)
    def supports_archive(self) -> bool:
        return True

    def archive_name(self, storage: Storage) -> str:
        return f"csis-{self._gce_resource_name(storage.get_name())}-archive"

    def _storage_script(self, storage: Storage, name: str, body: str) -> ExecutableModel:
        wd = self.get_path_for_phase(ExecutionLifecyclePhase.STORAGE_GENERATION, suffix=".tf").parent
        target = self._get_context().generation_path / wd / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("#!/usr/bin/env bash\nset -uo pipefail\n" + body)
        e = ExecutableModel(name="bash", type_="executable", binary="bash")
        e.args = [name]
        e.working_directory = wd
        return e

    def transition_actions(self, storage: Storage, from_state: str | None,
                           to_state: str) -> list[ExecutableModel]:
        disk, snap = self._gce_resource_name(storage.get_name()), self.archive_name(storage)
        project, zone = self._project(), self._disk_zone(storage)
        gcloud = shlex.quote(self._gcloud())
        if to_state == STORAGE_STATE_ARCHIVED and from_state == STORAGE_STATE_ACTIVE:
            self._require_script_inputs(storage, project=project, zone=zone)
            # snapshot the disk BEFORE terraform destroys it; a snapshot left by
            # an earlier attempt is reused (the archive is the name)
            return [self._storage_script(storage, f"archive-{disk}.sh",
                f'if {gcloud} compute snapshots describe "{snap}" --project "{project}" >/dev/null 2>&1; then\n'
                f'  echo "archive {snap} already exists"; exit 0\nfi\n'
                f'{gcloud} compute disks snapshot "{disk}" --snapshot-names "{snap}" --zone "{zone}" '
                f'--project "{project}" --quiet\n')]
        if to_state == STORAGE_STATE_DESTROYED and from_state == STORAGE_STATE_ARCHIVED:
            self._require_script_inputs(storage, project=project)
            # the disk is already gone; the archive goes with the demise
            return [self._storage_script(storage, f"unarchive-{disk}.sh",
                f'{gcloud} compute snapshots delete "{snap}" --project "{project}" --quiet 2>&1 '
                f'| grep -v "was not found" || true\n')]
        return []

    def post_transition_actions(self, storage: Storage, from_state: str | None,
                                to_state: str) -> list[ExecutableModel]:
        disk, snap = self._gce_resource_name(storage.get_name()), self.archive_name(storage)
        project = self._project()
        if from_state == STORAGE_STATE_ARCHIVED and to_state == STORAGE_STATE_ACTIVE:
            self._require_script_inputs(storage, project=project)
        gcloud = shlex.quote(self._gcloud())
        if from_state == STORAGE_STATE_ARCHIVED and to_state == STORAGE_STATE_ACTIVE:
            # restored: the data is on the disk again; the archive is deleted
            return [self._storage_script(storage, f"restore-{disk}.sh",
                f'{gcloud} compute snapshots delete "{snap}" --project "{project}" --quiet\n')]
        return []

    def _lookup(self, storage: Storage) -> dict[str, Any] | None:
        from google.cloud import compute_v1  # noqa: PLC0415
        from cs_image_system.gcloud_runtime.gcp_utils import make_credentials, resolve_project
        rtb = self._runtime()
        to_cfg: Any = getattr(getattr(rtb, "model", None), "self_to_gcp_client_config", None)
        cfg: dict[str, Any] = cast(dict[str, Any], to_cfg()) if callable(to_cfg) else {}
        project, zone = resolve_project(cfg), self._disk_zone(storage)
        if not project or not zone:
            raise RuntimeError("no project/zone to query")
        creds = make_credentials(cfg)
        client = compute_v1.DisksClient(credentials=creds) if creds else compute_v1.DisksClient()
        if self._get_context().meta_state.storage_state(storage.get_name()) == STORAGE_STATE_ARCHIVED:
            # archived (stage 11.6): the disk is expected absent; the archive
            # snapshot is what must exist
            try:
                snap = compute_v1.SnapshotsClient(credentials=creds).get(project=project, snapshot=self.archive_name(storage)) \
                    if creds else compute_v1.SnapshotsClient().get(project=project, snapshot=self.archive_name(storage))
            except Exception as e:  # noqa: BLE001
                if "404" in str(e) or "not found" in str(e).lower():
                    return None
                raise
            return {"id": snap.name, "state": "archived", "snapshot": snap.name, "tags": dict(getattr(snap, "labels", {}) or {})}
        try:
            d = client.get(project=project, zone=zone, disk=self._gce_resource_name(storage.get_name()))
        except Exception as e:  # NotFound -> absent; anything else -> unavailable
            if e.__class__.__name__ == "NotFound":
                return None
            raise
        labels = dict(getattr(d, "labels", {}) or {})
        if self._theirs(labels):
            return self._elsewhere_by_labels(labels, "a persistent disk")    # stage 93
        return {"id": d.name, "state": str(getattr(d, "status", "")), "size": int(getattr(d, "size_gb", 0)),
                "tags": labels}


S = TypeVar("S", bound=TofuFilestoreStorageBuilderModel)
class TofuFilestoreStorageBuilder(TofuGcpStorageBuilder[S]):
    @classmethod
    def csis_name(cls) -> str:
        return TF_GCP_FILESTORE

    @classmethod
    def capability_type(cls) -> str:
        return "filestore"

    def attachment_cardinality(self) -> str:
        return CARDINALITY_MANY

    def base_image_prerequisites(self, os_family: str | None = None) -> list[str]:
        # the package that carries an NFS client per package format; the line is the OS type's
        from cs_image_system.base.os_types import os_type_for_family
        os_type = os_type_for_family(os_family)
        packages = {"deb": "nfs-common", "rpm": "nfs-utils", "apk": "nfs-utils"}
        pkg = os_type.package_install_command([packages[os_type.package_format()]], lock_timeout=PACKAGE_LOCK_TIMEOUT)
        return [f"# storage type 'filestore' prerequisites ({self.get_name()}): NFS mount tooling", pkg]

    def verify_commands(self, os_family: str | None = None) -> list[str]:
        return ["# verify: NFS mount tooling present",
                "command -v mount.nfs >/dev/null 2>&1 || command -v mount.nfs4 >/dev/null 2>&1"]

    # ------------------------------------------------------- launch hooks
    def launch_script_lines(self, mount: dict[str, Any], group: str | None) -> list[str]:
        """Mount the share over NFS (address and share name by reference as
        ``filestore["<storage>"]``), then make the group's subtree: Filestore
        has no access points, so the launch makes the subtree itself."""
        name, mp = mount["storage"], mount["mount_point"]
        return [
            *self.mount_header_lines(mount),
            f"FS_IP=\"${{filestore[\"{name}\"].ip_address}}\"",
            f"FS_SHARE=\"${{filestore[\"{name}\"].share_name}}\"",
            *self.fstab_mount_lines(mount, f"$FS_IP:/$FS_SHARE {mp} nfs defaults,_netdev,nofail 0 0"),
            *self.group_subtree_lines(mount, group),
        ]

    def launch_variables(self) -> tuple[str, ...]:
        return ("filestore",)

    def module_dirname(self) -> str:
        return "gcp_storage_filestore"

    def retag_storage(self, storage: Storage, tags: dict[str, str]) -> bool:
        import subprocess  # noqa: PLC0415
        from cs_image_system.gcloud_runtime.gcp_packer_source import gce_label
        project, zone = self._project(), self._zone()
        if not project or not zone:
            raise RuntimeError("no project/zone to retag in")
        if self._lookup(storage) is None:
            return False
        name = self._gce_resource_name(storage.get_name())
        pairs = ",".join(f"{gce_label(k)}={gce_label(str(v))}" for k, v in tags.items())
        res = subprocess.run([self._gcloud(), "filestore", "instances", "update", name, "--location", str(zone),
                              "--project", str(project), f"--update-labels={pairs}", "--quiet"],
                             capture_output=True, text=True, check=False)
        if res.returncode != 0:
            raise RuntimeError(f"gcloud filestore instances update {name}: {(res.stderr or '').strip()[-300:]}")
        return True

    def module_args(self, storage: Storage) -> dict[str, Any]:
        rtb = self._runtime()
        networking = getattr(rtb.model, "networking", None) if rtb else None
        args: dict[str, Any] = {
            "name": self._gce_resource_name(storage.get_name()),
            "tier": getattr(self.model, "tier", "BASIC_HDD"),
            "capacity_gb": getattr(self.model, "capacity_gb", 1024),
            "labels": self._labels(storage),
        }
        zone = self._zone()
        if zone:
            args["zone"] = zone
        network = getattr(networking, "network", None) if networking else None
        if network and network not in OOPS_DEFAULTS:
            args["network"] = network
        if storage_groups(storage):
            # No access points on Filestore: the per-group subtree is created
            # and chgrp'ed (gid by reference) at first mount by the launch
            # parameters; the module only records the intent as labels.
            args["group_subtrees"] = sorted(storage_groups(storage))
        if storage_public_read(storage):
            args["public_read"] = True
        return args

    def _lookup(self, storage: Storage) -> dict[str, Any] | None:
        """State-query parity for Filestore (stage 63 item 17): ``gcloud
        filestore instances describe`` through the runtime's declared gcloud
        (item 14), the same CLI path as GCS, no new client library. The
        instance is found by the name the module gives it, in the runtime's
        zone. Not found -> absent; any other failure -> the query reports it
        unavailable. Until 2026-09-25 there was no lookup, and the query
        dropped every Filestore builder without a word."""
        import json  # noqa: PLC0415
        import subprocess  # noqa: PLC0415
        project, zone = self._project(), self._zone()
        if not project or not zone:
            raise RuntimeError("no project/zone to query")
        name = self._gce_resource_name(storage.get_name())
        res = subprocess.run([self._gcloud(), "filestore", "instances", "describe", name,
                              "--location", str(zone), "--project", str(project), "--format=json"],
                             capture_output=True, text=True, check=False)
        if res.returncode != 0:
            err = (res.stderr or "").strip()
            if "not found" in err.lower() or "NOT_FOUND" in err or "404" in err:
                return None
            raise RuntimeError(f"gcloud filestore instances describe {name}: {err[-300:]}")
        info = json.loads(res.stdout or "{}")
        shares = info.get("fileShares") or [{}]
        labels = dict(info.get("labels") or {})
        if self._theirs(labels):
            return self._elsewhere_by_labels(labels, "a Filestore share")     # stage 93
        rec: dict[str, Any] = {"id": str(info.get("name") or name).rsplit("/", 1)[-1],
                               "state": str(info.get("state") or ""),
                               "tags": labels}
        cap = shares[0].get("capacityGb")
        if cap is not None:
            rec["size"] = int(cap)
        return rec


