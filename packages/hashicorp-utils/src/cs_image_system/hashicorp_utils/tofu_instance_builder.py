"""The provider-neutral instance root.

One terraform workspace per instance builder, one ``module`` call per
instance against a module the provider names, driven by OpenTofu. The base
owns what no provider owns: the root's layout and header, the provider
requirement and configuration as hooks, the per-instance image variable
finalization fills from the packer manifests, the ephemeral toggle, the
enrollment-token variable, the state-manager binding and the remote-state
references (storage outputs and identity gids by reference), the runner
lines (fmt, init, validate, then the gated plan, gate and apply), detach
and unmount steps, replacements, the decommission whitelist, and the two
finalization hooks that pin an instance to the build it launched from.

A provider's root subclasses this and answers the hooks: which provider
and how it is configured, which module directory, which resource type a
replacement names, how a launch script reaches the machine, what the
module call carries, and any root-level blocks of its own (an AWS root
makes the instances' security group here). The hooks are the whole
difference between a cloud root and a container root; everything else is
the same terraform.
"""
