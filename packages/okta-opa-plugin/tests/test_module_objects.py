"""Hygiene XIV item 6: a group's resource group and policies read back against
what the identity module makes.

Records in the live API's shape (read 2026-10-23): the module's own objects
match; the 2026-10-19 rewrite of `basic` (delegated admin, rule name,
descriptions) is named field by field; an added label is a difference; a
reference that carries an id alone is not guessed; absent objects say so;
and the expectations are held to tfmodules/okta_opa_module/main.tf.
"""
from __future__ import annotations

import copy
from pathlib import Path

from cs_image_system.okta_opa_plugin.module_objects import expected, module_objects_state

REPO = Path(__file__).resolve().parents[3]


def _rule(g: str, admin: bool, labels: dict[str, str] | None = None) -> dict:
    return {"id": "r", "name": f"allow_login_{g}",
            "conditions": [{"condition_type": "gateway",
                            "condition_value": {"traffic_forwarding": True, "session_recording": False}}],
            "privileges": [{"privilege_type": "principal_account_ssh",
                            "privilege_value": {"_type": "principal_account_ssh", "enabled": True,
                                                "admin_level_permissions": admin}}],
            "resource_selector": {"_type": "server_based_resource", "selectors": [
                {"selector_type": "server_label",
                 "selector": {"_type": "server_label",
                              "server_selector": {"labels": labels or {"sftd.tx.group": g, "system.os_type": "linux"}},
                              "account_selector_type": "none", "account_selector": {"_type": "none"}}}]}}


def _policy(g: str, kind: str) -> dict:
    return {"id": f"p-{kind}", "name": f"{g}_v1_security_policy_{kind}",
            "description": f"Security policy for Okta group {g}_{kind}", "active": True,
            "resource_group": {"id": "rg-1", "name": f"{g}_rg"},
            "principals": {"user_groups": [{"id": "u", "name": f"{g}_{kind}", "type": "user_group"}],
                           "workload_roles": []},
            "rules": [_rule(g, kind == "admin")]}


def _rg(g: str) -> dict:
    return {"id": "rg-1", "name": f"{g}_rg", "description": f"Resource group for Okta group {g}",
            "delegated_resource_admin_groups": [{"id": "a", "name": f"{g}_admin", "type": "user_group"}]}


def _world(g: str = "coops"):
    return _rg(g), [_policy(g, "user"), _policy(g, "admin"), _policy("other", "user")]


def test_the_modules_own_objects_match():
    rg, policies = _world()
    state = module_objects_state("coops", rg, policies)
    assert state == {"resource_group": {"name": "coops_rg", "present": True},
                     "user_policy": {"name": "coops_v1_security_policy_user", "present": True},
                     "admin_policy": {"name": "coops_v1_security_policy_admin", "present": True}}


def test_the_2026_10_19_rewrite_of_basic_is_named_field_by_field():
    rg, policies = _world("basic")
    rg["delegated_resource_admin_groups"] = [{"id": "x", "name": "admin_admin", "type": "user_group"}]
    rg["description"] = "Resource group for Okta group basic_admin generated by OktaTFResourceGroup"
    for p in policies[:2]:
        p["rules"][0]["name"] = "allow_login_admin"
        p["description"] += " generated by OktaTFSecurityPolicyV1"
    state = module_objects_state("basic", rg, policies)
    assert "delegated_admins: ['admin_admin'] != ['basic_admin']" in state["resource_group"]["diff"]
    assert any(d.startswith("description: 'Resource group for Okta group basic_admin generated") for d in
               state["resource_group"]["diff"])
    for key in ("user_policy", "admin_policy"):
        assert "rules[0].name: 'allow_login_admin' != 'allow_login_basic'" in state[key]["diff"]
        assert any(d.startswith("description:") for d in state[key]["diff"])


def test_an_added_label_or_a_raised_privilege_is_a_difference():
    rg, policies = _world()
    policies[0]["rules"][0] = _rule("coops", False, {"sftd.tx.group": "coops", "system.os_type": "linux", "env": "x"})
    policies[1]["rules"][0]["privileges"][0]["privilege_value"]["admin_level_permissions"] = False
    state = module_objects_state("coops", rg, policies)
    assert any(d.startswith("rules[0].labels:") and "'env=x'" in d for d in state["user_policy"]["diff"])
    assert "rules[0].admin_level_permissions: False != True" in state["admin_policy"]["diff"]


def test_the_documented_nested_selector_shape_is_read_too():
    rg, policies = _world()
    for p in policies:
        rs = p["rules"][0]["resource_selector"]
        p["rules"][0]["resource_selector"] = {"selector_type": "server_based_resource",
                                              "selector": {"selectors": rs["selectors"]}}
    assert "diff" not in module_objects_state("coops", rg, policies)["user_policy"]


def test_a_reference_by_id_alone_is_not_guessed():
    rg, policies = _world()
    rg["delegated_resource_admin_groups"] = [{"id": "a"}]
    policies[0]["principals"]["user_groups"] = [{"id": "u"}]
    state = module_objects_state("coops", rg, policies)
    assert "diff" not in state["resource_group"] and "diff" not in state["user_policy"]


def test_absent_objects_say_so():
    _, policies = _world()
    state = module_objects_state("coops", None, copy.deepcopy(policies[:1]))
    assert state["resource_group"] == {"name": "coops_rg", "present": False}
    assert state["admin_policy"] == {"name": "coops_v1_security_policy_admin", "present": False}
    assert state["user_policy"]["present"] is True


def test_the_expectations_are_the_modules():
    main = (REPO / "tfmodules" / "okta_opa_module" / "main.tf").read_text()
    for needle in ('description                     = "Resource group for Okta group ${var.group_id}"',
                   'local.rg_delegated_admins', '[oktapam_group.admin.id]',
                   'description    = "Security policy for Okta group ${local.user_group}"',
                   'description    = "Security policy for Okta group ${local.admin_group}"',
                   'name = "allow_login_${var.group_id}"', '"system.os_type" = "linux"',
                   '"sftd.tx.group"  = var.group_id', 'admin_level_permissions = false',
                   'admin_level_permissions = true', 'traffic_forwarding = true', 'session_recording  = false'):
        assert needle in main, f"the module no longer says {needle!r}; module_objects.expected must follow it"
    want = expected("g")
    assert want["resource_group"]["delegated_admins"] == ["g_admin"]
    assert want["user_policy"]["rules"][0]["admin_level_permissions"] is False
    assert want["admin_policy"]["rules"][0]["admin_level_permissions"] is True
    # the builder passes no delegated admins and no extra labels, so the module's defaults hold:
    # every group's module call in the golden emission says so
    calls = sorted((REPO / "tests" / "fixtures" / "v2_golden" / "generated" / "identity").rglob("*-group-generation-group-*.tf"))
    assert calls, "the golden emission carries the group module calls"
    for call in calls:
        text = call.read_text()
        assert "delegated_admin_group_ids = []" in text and "server_labels" not in text, call.name
