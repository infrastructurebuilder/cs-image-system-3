    def post_finalize_phase(self, phase: ExecutionLifecyclePhase) -> None:
        """After this builder's packer builds ran, resolve PSIs from manifests.

        Each block dir contains a packer manifest recording the artifacts of the
        run; every built image's ProviderSpecificImage is upgraded from deferred
        (name-pattern) to resolved (concrete AMI id) so downstream consumers
        (e.g. the instance terraform) can pin the exact artifact.
        """
        if phase != ExecutionLifecyclePhase.IMAGE_GENERATION:
            return
        ctx = GlobalTypeContext()
        rtb = ctx.runtime_builders.get(self.model.get_runtime_provider(), None)
        if rtb is None:
            log.warning(f"No runtime builder for {self.get_display_name()}; "
                        "cannot resolve built images from manifests")
            return
        blocks, block_map = self.get_blocks()
        images_by_name: dict[str, Image | BaseImage] = {
            img.get_name(): img for imgs in block_map.values() for img in imgs}
        built: dict[str, str] = {}
        for block in blocks:
            manifest = (ctx.generation_path
                        / self.get_block_directory_for_phase(phase, block=block)
                        / MANIFEST_FILENAME)
            for image_name, ami in parse_packer_manifest(manifest, rtb).items():
                log.info(f"Built image {image_name} -> {ami} (from {manifest})")
                rtb.create_provider_specific_image_resolved(
                    source_name=image_name,
                    source_kind=PSISourceKind.IMAGE,
                    identifier=ami,
                    owner=SELF,
                )
                built[image_name] = ami
        # Lineage (DESIGN §3F4, N11, N23c): record every built artifact with
        # its stamp and mods; first-bind parent edges for images whose parent
        # was built this run.
        from cs_image_system.base.lineage import record_build

        def _resolve_parent(series: str) -> str | None:
            if series in built:
                return built[series]
            psi = ctx.get_provider_specific_image(series, rtb.get_name())
            return psi.identifier if psi is not None and psi.is_resolved() else None

        from cs_image_system.base.lineage import TAG_PREFIX
        for image_name, ami in built.items():
            image = images_by_name.get(image_name)
            if image is None:
                continue
            subconfig = image.get_image_runtime_subconfig_for_runtime(rtb.get_name())
            name = self._final_name(subconfig) if subconfig is not None else None
            record = record_build(ctx, image, rtb.get_name(), ami, name, _resolve_parent)
            # zero-drift-report: a parent resolved only after its bake leaves
            # generation-time `series:<name>`/stale-fingerprint tags on the
            # AMI. Lineage now holds the resolved truth; stamp it back
            # unconditionally -- create-tags is idempotent, and no detection
            # heuristic can be wrong.
            if record:
                rtb.retag_image(ami, {
                    f"{TAG_PREFIX}parent": str(record.get("parent", "")),
                    f"{TAG_PREFIX}fingerprint": str(record.get("input_fingerprint", ""))[:16],
                })

    def get_commands_to_run_after(
        self, phase: ExecutionLifecyclePhase
    ) -> CFExecutables:
        """Get a list of commands to run after a specific execution lifecycle event."""
        commands_now: list[ExecutableModel] = []
        commands_final: list[ExecutableModel] = []
        if  phase == ExecutionLifecyclePhase.IMAGE_GENERATION:
            blocks, block_map = self.get_blocks()
            for block in blocks:
                wd = self.get_block_path_for_phase(phase, block=block, suffix=".tf").parent
                assert wd is not None, (
                    f"Working directory for commands to run after {phase.value} cannot be "
                    f"None for builder {self.__class__.__name__}"
                )
                for cmd in [["fmt", "."], ["init", "."], ["validate","."]]:
                    e = self.get_executable_copy()
                    if not e:
                        raise ValueError(
                            f"Executable for {self.__class__.__name__} is not available "
                            f"but is required to run commands after {phase.value}"
                        )
                    e.args = cmd
                    e.working_directory = wd
                    commands_now.append(e)
                e = self.get_executable_copy()
                e.args = [
                    "build",
                    ".",
                ]  # This is the command that actually does the image building, so we put
                # it in the "after" list to run after all the setup and validation commands.
                e.working_directory = wd
                commands_final.append(e)
        return CFExecutables(commands_now, commands_final)

    @staticmethod
    def _final_name(subconfig) -> str | None:
        """The unique artifact name (DESIGN §3F4): the subconfig's templated
        final name with the run's execution values rendered. The
        ``execution.timestamp`` template never resolved through the field
        resolver (it is not a registered object), so it is rendered here."""
        name = subconfig.get_final_name() if subconfig is not None else None
        if not name:
            return name
        if "{{" in name:
            import jinja2
            ctx = GlobalTypeContext()
            dtfmt = getattr(ctx.read_config, "dateformat", None) or "%Y%m%d_%H%M%S"
            execution = {
                "timestamp": ctx.start_time.strftime(dtfmt),
                "date": ctx.start_time.date().isoformat(),
                "dateformat": dtfmt,
            }
            name = jinja2.Template(name).render(execution=execution)
        return name

    def get_blocks(self) -> tuple[list[str], dict[str, list[Image|BaseImage]]]:
        """Determine blocks of images that can be built together based on their dependencies.

        Under the V2 meta-workflow the current lifecycle selects the images:
        the base-image lifecycle builds only os-builder base images, the
        instance-image lifecycle only user images. With no lifecycle current
        (legacy flow) both ranges are emitted, base images first.
        """
        from cs_image_system.base.lifecycles import Lifecycle
        lifecycle = GlobalTypeContext().current_lifecycle
        blocks: list[str] = []
        block_map: dict[str, list[Image|BaseImage]] = {}
        images:list[Image|BaseImage] = (self.get_images(os_builder=True)  # type: ignore
                                        if lifecycle in (None, Lifecycle.BASE_IMAGE) else [])
        if images:
            # The first range of images is unaffected by the second range
            new_blocks, new_block_map = self.order_blocks_from_images(images)
            blocks.extend(new_blocks)
            for k,v in new_block_map.items():
                block_map.setdefault(k, []).extend(v)
        images = (self.get_images(os_builder=False)
                  if lifecycle in (None, Lifecycle.INSTANCE_IMAGE) else [])
        if images:
            # The second range of images must start after the first
            # So we jump the index by the number of blocks
            new_blocks, new_block_map = self.order_blocks_from_images(images, index_jump=len(blocks))
            blocks.extend(new_blocks)
            for k,v in new_block_map.items():
                block_map.setdefault(k, []).extend(v)
        return blocks, block_map

    def fetch_image_dependency_graph(self,images: list[Image|BaseImage]) -> dict[str, set[str]]:
        """Build the dependency graph for a list of images.

        Parameters
        ----------
        images : List[Image]
            Image objects to analyze for source-image dependencies.

        Returns
        -------
        Dict[str, Set[str]]
            Mapping of image names to their dependency names.
        """
        graph: dict[str, set[str]] = {image.get_name(): set() for image in images}
        # Ensure default is always present as a base image with no dependencies.
        # graph[SELF] = set()
        for image in images:
            if image.source_image in graph:
                graph.setdefault(image.get_name(), set()).add(image.source_image)
        return graph

    def fetch_work_list_order(self, graph: dict[str, set[str]]) -> list[set[str]]:
        """Fetch the work list order based on the image dependency graph.

        Parameters
        ----------
        graph : Dict[str, Set[str]]
            Mapping of image names to the image names they depend on.

        Returns
        -------
        List[Set[str]]
            Sets of image names, ordered by execution stage.
            Images inside the same set can run in parallel.
        """
        workset: dict[str, set[str]] = {}
        DEFAULT_KEY = "###"
        work_list: list[str] = [DEFAULT_KEY]
        # FIXME I'll bet there's a better way to do this...
        try:
            ts = TopologicalSorter(graph)
            for work_piece in ts.static_order():
                work_set = {work_piece} if isinstance(work_piece, str) else set(work_piece)
                for _work_item in work_set:
                    dep = graph[work_piece] if graph[work_piece] else DEFAULT_KEY
                    for d in dep:
                        if d not in work_list:
                            work_list.append(d)
                        workset.setdefault(d, set()).update(work_set)  # type: ignore
        except Exception as e:
            log.error(f"Error during topological sort of images: {e}")
            raise e
        retval =  [workset[k] for k in work_list if k in workset]
        return retval



    def order_blocks_from_images(self, images: list[Image|BaseImage], index_jump: int = 0) -> tuple[list[str], dict[str, list[Image|BaseImage]]]:
        _blocks: list[str] = []
        _block_map: dict[str, list[Image|BaseImage]] = {}

        image_map: dict[str, Image|BaseImage] = {image.get_name(): image for image in images}

        wlo: list[set[str]] = self.fetch_work_list_order(
                self.fetch_image_dependency_graph(images)
            )
        for idx, work_set in enumerate(wlo):
                _block_name = f"block-{idx+index_jump:03d}"
                _blocks.append(_block_name)
                # Sorted: work sets are Python sets, whose iteration order
                # changes per process (hash randomization); deterministic source
                # order keeps the generated build files reviewable.
                for image_name in sorted(work_set):
                    image = image_map.get(image_name, None)
                    if image:
                        _block_map.setdefault(_block_name, []).append(image)
                    else:
                        _block_map[_block_name] = []
        return _blocks, _block_map

