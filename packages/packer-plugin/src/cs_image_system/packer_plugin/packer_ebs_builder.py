    def image_to_source(self, type: str, runtime: str, image: Image|BaseImage) -> list[str]:
        """Convert an Image object to a list of packer 'source' lines for use in builds."""
        ctx = GlobalTypeContext()
        rtb = ctx.runtime_builders.get(self.model.runtime)
        assert rtb is not None, (
            f"Runtime builder must be available to convert image {image.name} "
            "to source configuration."
        )

        tags = copy.deepcopy(image.get_tags() or {})
        irtsc = image.get_image_runtime_subconfig_for_runtime(runtime)
        if not irtsc:
            raise ValueError(
                f"Image {image.name} does not have runtime-specific data for runtime "
                f"{runtime} required to convert to source configuration."
            )
        tags.update(irtsc.get_tags() or {})
        # Locate the provider-specific image for this image's source: the image's
        # own PSI when it builds from SELF (os-resolved base images, registered
        # during the resolution phase), otherwise the PSI of the source image it
        # chains from (resolved for base images, deferred for user images that a
        # prior block builds).
