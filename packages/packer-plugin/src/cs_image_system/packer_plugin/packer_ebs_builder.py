def parse_packer_manifest(manifest_path: Path, rtb: Any = None) -> dict[str, str]:
    """Parse a packer manifest into {image name: build id}.

    Only builds from the manifest's last run are considered. Build names are
    the packer source labels, which this builder sets to the image name; the
    runtime plugin turns ``artifact_id`` into its build id (amazon-ebs:
    '<region>:<ami-id>' -> ami id; googlecompute: the image name).
    """
    if not manifest_path.is_file():
        log.warning(f"No packer manifest at {manifest_path}; built image ids unavailable")
        return {}
    try:
        data = json.loads(manifest_path.read_text())
    except (OSError, json.JSONDecodeError) as e:
        log.error(f"Could not parse packer manifest {manifest_path}: {e}")
        return {}
    last_run = data.get("last_run_uuid")
    results: dict[str, str] = {}
    for build in data.get("builds", []):
        if last_run and build.get("packer_run_uuid") != last_run:
            continue
        name = build.get("name")
        artifact = build.get("artifact_id") or ""
        identifier = (rtb.build_id_from_artifact(artifact) if rtb is not None
                      else artifact.split(":")[-1]) if artifact else None
        if name and identifier:
            results[name] = identifier
    return results

