"""The volume storage builder (stage 103 branch 2).

One ``docker_volume`` per storage through tfmodules/docker_volume, on the
``kreuzwerker/docker`` provider, reusing the clouds' tofu storage machinery
(one terraform root per builder, a module call per storage, the storage
state machine, the apply gate). Capability type ``volume``: many containers
may mount one, it is POSIX (the per-group subtree is made and chgrp'ed at
first launch by the launch script), it lives in no zone, and the daemon
mounts it at the declared path before the container's first command
(``platform_mounts``). Archive is a later item: a volume has no snapshot.
"""
from __future__ import annotations

import json
import logging
import subprocess
from typing import Any, TypeVar, cast

from cs_image_system.base.basic.builder_base_storage import CARDINALITY_MANY
from cs_image_system.base.models.executable import ExecutableModel
from cs_image_system.base.models.storage import Storage
from cs_image_system.contract.assets import AssetSet
from cs_image_system.contract.lifecycle import ExecutionLifecyclePhase
from cs_image_system.docker_runtime.docker_names import tag_name
from cs_image_system.hashicorp_utils.collector import TerraformCollector
from cs_image_system.tf_ebs_instance_plugin.tf_storage_builder import TofuStorageBuilder, storage_groups

from .tf_docker_models import TF_DOCKER_VOLUME, TofuDockerVolumeStorageBuilderModel

log = logging.getLogger(__name__)

Q = TypeVar("Q", bound=TofuDockerVolumeStorageBuilderModel)
DOCKER_PROVIDER_SOURCE = "kreuzwerker/docker"


def volume_name(storage_name: str) -> str:
    """A docker volume name from a storage's name (letters, digits, ``_``,
    ``.`` and ``-``; the same rule as a tag)."""
    return tag_name(storage_name)


class TofuDockerVolumeStorageBuilder(TofuStorageBuilder[Q]):
    @classmethod
    def csis_name(cls) -> str:
        return TF_DOCKER_VOLUME

    @classmethod
    def capability_type(cls) -> str:
        return "volume"

    def attachment_cardinality(self) -> str:
        return CARDINALITY_MANY

    def is_zonal(self) -> bool:
        return False      # a daemon has no zones

    def platform_mounts(self) -> bool:
        return True       # the daemon mounts it at the declared path before the first command

    def base_image_prerequisites(self, os_family: str | None = None) -> list[str]:
        return [f"# storage type 'volume' declared: no prerequisites to bake ({self.get_name()})"]

    def module_dirname(self) -> str:
        return "docker_volume"

    # ------------------------------------------------------------ the daemon
    def _runtime(self):
        return self._get_context().runtime_builders.get(self.model.get_runtime_provider(), None)

    def get_executable_copy(self) -> ExecutableModel:
        """Every tofu process of this root reaches the runtime's daemon (the
        instance builder's rule)."""
        e = super().get_executable_copy()
        env_of = getattr(self._runtime(), "tool_environment", None)
        if callable(env_of):
            extra = cast(dict[str, str], env_of())
            e.environment = {**dict(e.environment or {}), **extra}
        return e

    def _docker(self, *args: str) -> subprocess.CompletedProcess[str]:
        """The runtime's own docker call when it has one (its binary, its
        daemon), else ``docker`` from PATH (a stand-in runtime in a test)."""
        rtb = self._runtime()
        call = getattr(rtb, "_docker", None)
        if callable(call):
            return cast(subprocess.CompletedProcess[str], call(*args, check=False))
        return subprocess.run(["docker", *args], capture_output=True, text=True, check=False)

    def generate_items_before(self, phase: ExecutionLifecyclePhase) -> AssetSet:
        items = AssetSet()
        if phase != ExecutionLifecyclePhase.STORAGE_GENERATION or not self._has_work():
            return items
        rpath = self.get_path_for_phase(phase, suffix=".tf")
        items = items.with_default_path(rpath)
        items.add(f"# Terraform configuration for container volumes generated by "
                  f"{self.__class__.__name__} ({self.name})")
        items.add("# The daemon's address is not here: every tofu process of this root carries the")
        items.add("# runtime's DOCKER_HOST or DOCKER_CONTEXT in its environment (stage 103 branch 2).")
        col = TerraformCollector()
        ws = self.name
        if self.model.required_plugins:
            for plugin in self.model.required_plugins:
                col.require_provider(ws, plugin.name, source=getattr(plugin, "source", None),
                                     version=getattr(plugin, "version", None))
        else:
            col.require_provider(ws, "docker", source=DOCKER_PROVIDER_SOURCE)
        col.configure_provider(ws, "docker", {})
        col.bind_workspace(ws, self.model.state_configuration, self.runtime_state_configuration())   # stage 46: own, runtime's, default
        for identity_ws in sorted(self.identity_workspaces()):
            col.reference_remote_state(ws, producer_workspace=identity_ws)
        items.add_list(col.generate_terraform_block(ws))
        items.add_list(col.generate_provider_blocks(ws))
        remote_lines = col.generate_remote_state_datasources(ws)
        if remote_lines:
            items.add_list(remote_lines)
        backend_lines = col.generate_backend_config(ws)
        if backend_lines:
            items.add_list(self._backend_config_path(phase), backend_lines)
        return items

    def _labels(self, storage: Storage) -> dict[str, str]:
        from cs_image_system.base.lineage import config_tags
        merged = getattr(self.model, "variables", None)
        base = merged.merged_tags(storage.tags) if merged is not None else dict(storage.tags or {})
        labels = {str(k): str(v) for k, v in base.items()}
        labels["csis_storage"] = storage.get_name()
        get_ctx: Any = getattr(self, "_get_context", None)      # a stand-in without a context gets no id
        if callable(get_ctx):
            labels.update(config_tags(cast(Any, get_ctx())))   # stage 93: the volume carries the id
        for g in sorted(storage_groups(storage)):
            labels[f"csis_group_{g}"] = "true"
        return labels

    def module_args(self, storage: Storage) -> dict[str, Any]:
        args: dict[str, Any] = dict(self.model.variables.as_module_args())   # driver, driver_opts when declared
        args["name"] = volume_name(storage.get_name())
        args["labels"] = self._labels(storage)
        return args

    # ------------------------------------------------------- state query
    def _lookup(self, storage: Storage) -> dict[str, Any] | None:
        """``docker volume inspect``: present with its driver, mountpoint and
        labels; absent when the daemon has no such volume; another
        configuration's volume of our name reads as elsewhere (stage 93)."""
        name = volume_name(storage.get_name())
        res = self._docker("volume", "inspect", name)
        if res.returncode != 0:
            err = (res.stderr or "").lower()
            if "no such volume" in err or "not found" in err:
                return None
            raise RuntimeError(f"docker volume inspect {name}: {(res.stderr or '').strip()[-300:]}")
        data = json.loads(res.stdout or "[]")
        if not data:
            return None
        info = dict(data[0])
        labels = {str(k): str(v) for k, v in dict(info.get("Labels") or {}).items()}
        from cs_image_system.base.lineage import belongs_to_another_configuration, owner_of
        if belongs_to_another_configuration(self._get_context(), labels):
            return {"present": False, "elsewhere": owner_of(labels), "what": "a volume"}
        return {"id": str(info.get("Name") or name), "state": "active", "driver": str(info.get("Driver") or ""),
                "mountpoint": str(info.get("Mountpoint") or ""), "tags": labels}

    def retag_storage(self, storage: Storage, tags: dict[str, str]) -> bool:
        """A volume's labels are fixed when it is created and a change would
        replace it WITH ITS DATA: relabel reports and nothing re-creates."""
        raise NotImplementedError(
            f"volume {volume_name(storage.get_name())}: a volume's labels are fixed when it is created; "
            f"it would carry {', '.join(f'{k}={v}' for k, v in sorted(tags.items()))} only as a new volume")

    def transition_actions(self, storage: Storage, from_state: str | None, to_state: str) -> list[ExecutableModel]:
        """``destroyed``: terraform removes the volume, and its data goes with
        it (N19: wiped clean). Archive is a later item."""
        return []
